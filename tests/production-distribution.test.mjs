import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {packProduction, verifyProductionDistribution, verifyProductionPack} from '../tools/verify-production-distribution.mjs';
import {verifyPackedInstall} from '../tools/verify-packed-install.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

async function fixture(t) {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'refas-production-package-'));
  t.after(() => fs.rm(root, {recursive: true, force: true}));
  for (const relative of ['package.json', 'README.md', 'LICENSE', 'bin', 'skills', '.codex-plugin', '.claude-plugin']) {
    await fs.cp(path.join(ROOT, relative), path.join(root, relative), {recursive: true});
  }
  return root;
}

test('actual npm tarball installs only the production CLI and a standalone Python skill', async () => {
  const result = await verifyPackedInstall();
  assert.equal(result.status, 'PASS');
  assert.deepEqual(result.exitStatuses, [0, 1, 2, 127]);
  assert.equal(result.plainSkillWithoutNodeOrSitePackages, true);
});

test('npm excludes repository-only legacy, schemas and generated bytecode', async t => {
  const root = await fixture(t);
  for (const relative of ['legacy/v1/scripts/old.mjs', 'schemas/old.schema.json', 'skills/refas/scripts/production/__pycache__/project.cpython-312.pyc']) {
    await fs.mkdir(path.dirname(path.join(root, relative)), {recursive: true});
    await fs.writeFile(path.join(root, relative), 'repository-only probe');
  }
  const pack = packProduction({root});
  assert.equal((await verifyProductionDistribution({root, pack})).status, 'PASS');
});

test('accidentally restoring legacy code inside the skill fails both folder and actual npm payload checks', async t => {
  const root = await fixture(t);
  const old = 'skills/refas/scripts/lib/canonical.mjs';
  await fs.mkdir(path.dirname(path.join(root, old)), {recursive: true});
  await fs.copyFile(path.join(ROOT, 'legacy/v1/scripts/lib/canonical.mjs'), path.join(root, old));
  const destination = path.join(root, 'packed');
  await fs.mkdir(destination);
  const pack = packProduction({root, destination});
  const tar = spawnSync('tar', ['-tzf', path.join(destination, pack.filename)], {encoding: 'utf8'});
  assert.equal(tar.status, 0, tar.stderr);
  const files = tar.stdout.trim().split('\n').filter(name => !name.endsWith('/')).map(name => ({path: name.slice('package/'.length), size: 0}));
  assert.ok(files.some(file => file.path === old), 'probe must actually enter the tarball');
  assert.throws(() => verifyProductionPack({...pack, files}), /undeclared files.*canonical\.mjs/u);
  await assert.rejects(verifyProductionDistribution({root}), /undeclared files.*canonical\.mjs/u);
});

test('production metadata cannot expose the legacy host, library API or a mismatched runtime version', async t => {
  const root = await fixture(t);
  const original = JSON.parse(await fs.readFile(path.join(root, 'package.json'), 'utf8'));
  for (const [change, message] of [
    [{version: '1.4.2'}, /versions must match/u],
    [{bin: {...original.bin, 'refas-host': 'legacy/v1/scripts/refas-host.mjs'}}, /only the production launcher/u],
    [{exports: {'.': './legacy/v1/scripts/lib/index.mjs'}}, /legacy JavaScript API/u],
  ]) {
    await fs.writeFile(path.join(root, 'package.json'), JSON.stringify({...original, ...change}));
    await assert.rejects(verifyProductionDistribution({root}), message);
  }
});
